function jitter(text) {
  // 좌표를 모르는 동네를 권역 중심 주변에 흩어 놓기 위한, 이름에서 얻는 고정 난수
  let hash = 0;
  for (const ch of text) hash = (hash * 31 + ch.codePointAt(0)) % 9973;
  const angle = (hash / 9973) * Math.PI * 2;
  return [Math.cos(angle) * 0.03, Math.sin(angle) * 0.02];
}

const NUMERALS = { 1: "일", 2: "이", 3: "삼", 4: "사" };

/** 행정동 이름("제주시 일도1동")을 법정동 좌표표의 이름("일도일동")으로 바꾼다. 읍면은 이름이 같다. */
function emdToArea(emd) {
  const [city, ...rest] = emd.split(" ");
  const name = rest.join(" ").replace(/(\d)동$/, (_, digit) => `${NUMERALS[digit] || digit}동`);
  return `${city} ${name}`;
}

/** 진단 결과의 한 행이 섬 위 어디에 서야 하는지 돌려준다. */
export function locate(row) {
  if (row.emd_nm) {
    const known = AREAS[emdToArea(row.emd_nm)];
    if (known) return known;
    const city = row.emd_nm.split(" ")[0];
    const base = REGIONS[row.dstrct_se] || CITIES[city] || CENTER;
    const [dx, dy] = jitter(row.emd_nm);
    return [base[0] + dx, base[1] + dy];
  }
  if (row.bjd) {
    const city = (row.dstrct_se || "").split(" ")[0];
    const known = AREAS[`${city} ${row.bjd}`] || AREAS[emdToArea(`${city} ${row.bjd}`)];
    if (known) return known;
    const base = REGIONS[row.dstrct_se] || CITIES[city] || CENTER;
    const [dx, dy] = jitter(row.bjd);
    return [base[0] + dx, base[1] + dy];
  }
  if (row.dstrct_se) return REGIONS[row.dstrct_se] || CITIES[row.dstrct_se.split(" ")[0]] || CENTER;
  if (row.city) return CITIES[row.city] || CENTER;
  return [CENTER[0], CENTER[1] + 0.07];
}
